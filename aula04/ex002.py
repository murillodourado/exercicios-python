#Ex. 3 - Retorno o valor final da equação do segundo grau, tendo em vista que o usuário poderá inserir o valor de x.

# 10X + 5X + 2 = 0 

valor_x = int(input('De acordo com a equação 10X + 5x + 2 = 0, qual número você deseja substituit pelo X?: '))
calculo = (10 * valor_x) + (5 * valor_x) + 2 

print(f'O resultado é {calculo}')